// Writes apps/web/.env.local from the running local Supabase stack.
// Local development and CI only: the keys are the Supabase CLI's local demo keys.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '../../..');

const raw = execFileSync('pnpm', ['exec', 'supabase', 'status', '-o', 'json'], {
  cwd: repoRoot,
  encoding: 'utf8',
});
const status = JSON.parse(raw.slice(raw.indexOf('{')));

const apiUrl = status.API_URL;
const anonKey = status.ANON_KEY ?? status.PUBLISHABLE_KEY;
const mailpitUrl = status.MAILPIT_URL ?? status.INBUCKET_URL ?? 'http://127.0.0.1:54324';
if (!apiUrl || !anonKey) {
  throw new Error('Could not read API_URL/ANON_KEY from `supabase status`. Is the stack running?');
}

const lines = [
  '# Generated by scripts/write-local-env.mjs. Local only; do not commit.',
  `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
  'NEXT_PUBLIC_SITE_URL=http://127.0.0.1:3000',
  `MAILPIT_URL=${mailpitUrl}`,
  '# Local demo service role. Used only by the payment webhook on this machine.',
  `SUPABASE_SERVICE_ROLE_KEY=${status.SERVICE_ROLE_KEY ?? status.SECRET_KEY}`,
  '# Playwright only (creates synthetic users). Never read by the web app.',
  `E2E_SUPABASE_SERVICE_ROLE_KEY=${status.SERVICE_ROLE_KEY ?? status.SECRET_KEY}`,
  '',
];
writeFileSync(resolve(here, '../.env.local'), lines.join('\n'));
process.stdout.write('Wrote apps/web/.env.local\n');
