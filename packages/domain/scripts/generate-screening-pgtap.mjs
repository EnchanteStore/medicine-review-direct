// Generates supabase/tests/004_safety_rule_cases.test.sql from the shared
// fixture so the database evaluator is tested against the same documented
// cases as the TypeScript evaluator. A Vitest check fails if it is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const fixturePath = resolve(here, '../src/safety/screening-test-cases.json');
export const outputPath = resolve(here, '../../../supabase/tests/004_safety_rule_cases.test.sql');

const q = (s) => `'${s.replaceAll("'", "''")}'`;

export function renderPgtap(fixture) {
  const lines = [
    '-- GENERATED by packages/domain/scripts/generate-screening-pgtap.mjs. Do not edit by hand.',
    `-- Documented screening cases for rule set ${fixture.ruleset_version} (DRAFT pending clinical approval).`,
    'begin;',
    'create extension if not exists pgtap with schema extensions;',
    `select plan(${fixture.cases.length * 2 + fixture.invalid.length + 1});`,
    '',
    `select is((select version from public.safety_rulesets where is_active), ${q(fixture.ruleset_version)}, 'active rule set matches the fixture version');`,
    '',
    "create function pg_temp.ans(o jsonb) returns jsonb language sql as $$",
    "  select (select jsonb_object_agg(x ->> 'id', 'no') from jsonb_array_elements(",
    "    (select definition from public.safety_rulesets where is_active) -> 'questions') x) || o",
    '$$;',
    "create function pg_temp.eval(o jsonb) returns jsonb language sql as $$",
    "  select app.evaluate_screening((select definition from public.safety_rulesets where is_active), pg_temp.ans(o))",
    '$$;',
    '',
  ];
  for (const c of fixture.cases) {
    const answers = q(JSON.stringify(c.answers));
    lines.push(
      `select is(pg_temp.eval(${answers}::jsonb) ->> 'outcome', ${q(c.outcome)}, ${q(`${c.name} -> ${c.outcome}`)});`,
      `select is(pg_temp.eval(${answers}::jsonb) -> 'flags', ${q(JSON.stringify(c.flags))}::jsonb, ${q(`${c.name} -> flags`)});`,
    );
  }
  lines.push('');
  for (const c of fixture.invalid) {
    lines.push(
      `select throws_ok($q$ select pg_temp.eval(${q(JSON.stringify(c.answers))}::jsonb) $q$, '22023', null, ${q(c.name)});`,
    );
  }
  lines.push('', 'select * from finish();', 'rollback;', '');
  return lines.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const fixture = JSON.parse(readFileSync(fixturePath, 'utf8'));
  writeFileSync(outputPath, renderPgtap(fixture));
  process.stdout.write(`Wrote ${outputPath}\n`);
}
